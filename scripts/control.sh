#!/usr/bin/env bash
# AttackBox Control (Web 控制端) 统一管理与部署脚本
# 用法:
#   sudo ./scripts/control.sh setup   [--database URL] [--origin URL] [--force]
#   sudo ./scripts/control.sh migrate
#   sudo ./scripts/control.sh admin   [--email EMAIL] [--password PWD] [--name NAME]
#   ./scripts/control.sh deploy
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="/etc/attackbox/web.env"
WEB_ROOT="/var/www/attackbox-web"

gen_hex32() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 32
    else
        od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
    fi
}

read_env_var() {
    local key="$1"
    if sudo test -f "${ENV_FILE}"; then
        sudo awk -F= -v k="${key}" '$1 == k {sub(/^[^=]*=/, ""); print; exit}' "${ENV_FILE}" | tr -d '\r'
    fi
}

cmd_setup() {
    local db_url=""
    local origin=""
    local host="127.0.0.1"
    local port="3000"
    local cluster_secret=""
    local worker_public_url=""
    local resend_key=""
    local mail_from=""
    local force="false"

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --database) db_url="$2"; shift 2 ;;
            --origin) origin="$2"; shift 2 ;;
            --host) host="$2"; shift 2 ;;
            --port) port="$2"; shift 2 ;;
            --cluster-secret) cluster_secret="$2"; shift 2 ;;
            --worker-public-url) worker_public_url="$2"; shift 2 ;;
            --resend-key) resend_key="$2"; shift 2 ;;
            --mail-from) mail_from="$2"; shift 2 ;;
            --force) force="true"; shift ;;
            *) echo "未知参数: $1" >&2; exit 1 ;;
        esac
    done

    if [[ -f "${ENV_FILE}" && "${force}" != "true" ]]; then
        if [[ ! -t 0 ]]; then
            echo "错误: ${ENV_FILE} 已存在，非交互模式请添加 --force" >&2
            exit 1
        fi
        read -r -p "${ENV_FILE} 已存在，是否覆盖并重新生成密钥？[y/N]: " confirm
        if [[ ! "${confirm}" =~ ^[Yy]$ ]]; then
            echo "已取消。"
            exit 0
        fi
    fi

    if [[ -z "${db_url}" ]]; then
        if [[ ! -t 0 ]]; then
            echo "错误: 非交互模式必须提供 --database" >&2
            exit 1
        fi
        read -r -p "PostgreSQL 连接地址 [postgres://attackbox:CHANGE_ME@127.0.0.1:5432/attackbox_db]: " db_url
        db_url="${db_url:-postgres://attackbox:CHANGE_ME@127.0.0.1:5432/attackbox_db}"
    fi

    if [[ -z "${origin}" ]]; then
        if [[ ! -t 0 ]]; then
            echo "错误: 非交互模式必须提供 --origin" >&2
            exit 1
        fi
        read -r -p "网站访问地址 (APP_BASE_URL) [http://127.0.0.1]: " origin
        origin="${origin:-http://127.0.0.1}"
    fi

    # 去除末尾斜杠
    origin="${origin%/}"

    if [[ ! "${db_url}" =~ ^postgres(ql)?://[^:@/]+:[^@/]+@[^:/]+(:[0-9]+)?/.+ ]]; then
        echo "错误: PostgreSQL 连接地址格式无效，需包含用户名、密码、主机与数据库名" >&2
        exit 1
    fi

    if [[ ! "${origin}" =~ ^https?://[^/]+$ ]]; then
        echo "错误: 网站访问地址必须以 http:// 或 https:// 开头且不包含路径" >&2
        exit 1
    fi

    if [[ -z "${cluster_secret}" ]]; then
        cluster_secret="$(gen_hex32)"
    fi
    if [[ ${#cluster_secret} -lt 32 ]]; then
        echo "错误: SANDBOX_CLUSTER_SECRET 长度至少为 32 字符" >&2
        exit 1
    fi

    if [[ -z "${worker_public_url}" ]]; then
        if [[ "${origin}" =~ ^https:// ]]; then
            worker_public_url="wss://127.0.0.1:8443"
        else
            worker_public_url="ws://127.0.0.1:8443"
        fi
    fi

    local signing_seed
    local content_key
    local quiz_secret
    signing_seed="$(gen_hex32)"
    content_key="$(gen_hex32)"
    quiz_secret="$(gen_hex32)"
    local nodes_json="[{\"id\":\"node-primary\",\"label\":\"Primary Node\",\"publicDataUrl\":\"${worker_public_url}\",\"maxSlots\":16}]"

    mkdir -p "$(dirname "${ENV_FILE}")"
    local tmp_file="${ENV_FILE}.tmp.$$"
    umask 0077
    cat > "${tmp_file}" <<EOF
# Generated by scripts/control.sh setup; mode 0600
NODE_ENV=production
PORT=${port}
HOST=${host}
DATABASE_URL=${db_url}
SANDBOX_CONTROL_ENABLED=true
SANDBOX_SCHEDULING_ENABLED=true
SANDBOX_CLUSTER_SECRET=${cluster_secret}
SANDBOX_SIGNING_SEED_HEX=${signing_seed}
SANDBOX_NODES_JSON=${nodes_json}
CONTENT_DATA_DIR=/var/lib/attackbox-web/content
LAB_DATA_DIR=/var/lib/attackbox-web/labs
CONTENT_CREDENTIALS_KEY=${content_key}
QUIZ_ANSWER_HMAC_SECRET=${quiz_secret}
RESEND_API_KEY=${resend_key}
MAIL_FROM=${mail_from}
APP_BASE_URL=${origin}
EOF
    chmod 0600 "${tmp_file}"
    if id -u attackbox >/dev/null 2>&1; then
        chown root:attackbox "${tmp_file}"
        chmod 0640 "${tmp_file}"
    fi
    mv -f "${tmp_file}" "${ENV_FILE}"

    echo "==> Control 配置文件已写入: ${ENV_FILE}"
    echo "==> 集群密钥 (SANDBOX_CLUSTER_SECRET): ${cluster_secret}"
    echo "    提示: 同机部署 Worker 时 worker.sh setup 会自动读取此密钥；异机部署请通过 --cluster-secret 传入。"
}

cmd_migrate() {
    if ! sudo test -f "${ENV_FILE}"; then
        echo "错误: 缺少 ${ENV_FILE}，请先运行: sudo ./scripts/control.sh setup" >&2
        exit 1
    fi
    local db_url
    db_url="$(read_env_var DATABASE_URL)"
    if [[ -z "${db_url}" ]]; then
        echo "错误: ${ENV_FILE} 中缺少 DATABASE_URL" >&2
        exit 1
    fi
    echo "==> [Control Migrate] 执行数据库迁移..."
    cd "${REPO_ROOT}/web"
    DATABASE_URL="${db_url}" node server/scripts/apply-migrations.mjs
}

cmd_admin() {
    if ! sudo test -f "${ENV_FILE}"; then
        echo "错误: 缺少 ${ENV_FILE}，请先运行: sudo ./scripts/control.sh setup" >&2
        exit 1
    fi
    local db_url
    db_url="$(read_env_var DATABASE_URL)"
    if [[ -z "${db_url}" ]]; then
        echo "错误: ${ENV_FILE} 中缺少 DATABASE_URL" >&2
        exit 1
    fi

    local email=""
    local password=""
    local name="Administrator"

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --email) email="$2"; shift 2 ;;
            --password) password="$2"; shift 2 ;;
            --name) name="$2"; shift 2 ;;
            *) echo "未知参数: $1" >&2; exit 1 ;;
        esac
    done

    if [[ -z "${email}" || -z "${password}" ]]; then
        if [[ ! -t 0 ]]; then
            echo "错误: 非交互模式请提供 --email 与 --password" >&2
            exit 1
        fi
        read -r -p "管理员邮箱: " email
        read -r -p "显示名称 [Administrator]: " input_name
        name="${input_name:-Administrator}"
        read -r -s -p "管理员密码（至少 12 位）: " password
        echo ""
        read -r -s -p "再次输入密码: " password_confirm
        echo ""
        if [[ "${password}" != "${password_confirm}" ]]; then
            echo "错误: 两次密码不一致" >&2
            exit 1
        fi
    fi

    cd "${REPO_ROOT}/web"
    ADMIN_EMAIL="${email}" ADMIN_PASSWORD="${password}" ADMIN_NAME="${name}" \
        node -e 'process.stdout.write(JSON.stringify({email:process.env.ADMIN_EMAIL.trim().toLowerCase(),password:process.env.ADMIN_PASSWORD,displayName:process.env.ADMIN_NAME.trim()||"Administrator"}))' \
        | DATABASE_URL="${db_url}" node server/scripts/init-admin.mjs
}

cmd_deploy() {
    local stage_root="/var/www/.attackbox-web-stage.$$"
    local prev_root="/var/www/.attackbox-web-prev.$$"
    trap 'sudo rm -rf "${stage_root}"' EXIT

    if ! sudo test -f "${ENV_FILE}"; then
        echo "错误: 缺少 ${ENV_FILE}，请先运行: sudo ./scripts/control.sh setup" >&2
        exit 1
    fi

    if [[ ! -f "${REPO_ROOT}/web/.output/server/index.mjs" ]]; then
        echo "错误: 缺少编译产物 web/.output/server/index.mjs，请先运行: ./scripts/build.sh control" >&2
        exit 1
    fi

    local web_host
    local web_port
    web_host="$(read_env_var HOST)"
    web_port="$(read_env_var PORT)"
    web_host="${web_host:-127.0.0.1}"
    web_port="${web_port:-3000}"
    local web_upstream="${web_host}:${web_port}"

    echo "==> [Control Deploy] 准备运行账户与持久化数据目录..."
    if ! id -u attackbox >/dev/null 2>&1; then
        sudo useradd --system --home-dir /var/lib/attackbox-web --create-home --shell /usr/sbin/nologin attackbox
    fi
    sudo install -d -m 0750 -o root -g attackbox /etc/attackbox
    sudo chown root:attackbox "${ENV_FILE}"
    sudo chmod 0640 "${ENV_FILE}"
    sudo install -d -m 0700 -o attackbox -g attackbox \
        /var/lib/attackbox-web \
        /var/lib/attackbox-web/content \
        /var/lib/attackbox-web/labs

    echo "==> [Control Deploy] 发布 web/.output -> ${WEB_ROOT}/.output..."
    sudo rm -rf "${stage_root}" "${prev_root}"
    sudo mkdir -p "${stage_root}"
    sudo cp -a "${REPO_ROOT}/web/.output" "${stage_root}/.output"
    sudo chown -R root:root "${stage_root}"

    echo "==> [Control Deploy] 渲染 Nginx 与 systemd 单元..."
    sed "s|@@WEB_UPSTREAM@@|${web_upstream}|g" "${REPO_ROOT}/deploy/control/nginx.conf.template" \
        | sudo tee /etc/nginx/sites-available/attackbox >/dev/null
    sudo ln -sfn /etc/nginx/sites-available/attackbox /etc/nginx/sites-enabled/attackbox
    sudo rm -f /etc/nginx/sites-enabled/default
    sudo nginx -t

    sudo cp "${REPO_ROOT}/deploy/control/attackbox-web.service" /etc/systemd/system/attackbox-web.service
    sudo systemctl daemon-reload

    if sudo test -d "${WEB_ROOT}"; then
        sudo mv "${WEB_ROOT}" "${prev_root}"
    fi
    sudo mv "${stage_root}" "${WEB_ROOT}"
    sudo rm -rf "${prev_root}"

    echo "==> [Control Deploy] 启动 attackbox-web 与 nginx..."
    sudo systemctl enable attackbox-web nginx >/dev/null
    sudo systemctl restart attackbox-web
    sudo systemctl reload nginx

    echo "==> [Control Deploy] 执行健康检查 (http://${web_upstream}/)..."
    for _ in $(seq 1 30); do
        if curl --fail --silent --show-error --max-time 2 "http://${web_upstream}/" >/dev/null; then
            echo "==> [Control Deploy] 部署成功，Control 服务运行正常。"
            return 0
        fi
        sleep 1
    done

    echo "错误: attackbox-web 健康检查超时，请查看: sudo journalctl -u attackbox-web -n 50" >&2
    exit 1
}

ACTION="${1:-}"
shift || true

case "${ACTION}" in
    setup)   cmd_setup "$@" ;;
    migrate) cmd_migrate "$@" ;;
    admin)   cmd_admin "$@" ;;
    deploy)  cmd_deploy "$@" ;;
    *)
        echo "用法: $0 {setup|migrate|admin|deploy} [参数...]" >&2
        exit 1
        ;;
esac
