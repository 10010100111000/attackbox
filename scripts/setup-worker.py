#!/usr/bin/env python3
"""Generate /etc/attackbox/worker.yaml for an AttackBox Worker node."""
import argparse
import os
from pathlib import Path
import sys
from urllib.parse import urlsplit

DEFAULT_WORKER_CONFIG = Path('/etc/attackbox/worker.yaml')
DEFAULT_CONTROL_ENV = Path('/etc/attackbox/web.env')


def prompt(label, default=''):
    text = f'{label} [{default}]: ' if default else f'{label}: '
    value = input(text).strip()
    return value or default


def read_local_cluster_secret():
    if not DEFAULT_CONTROL_ENV.exists():
        return ''
    try:
        for line in DEFAULT_CONTROL_ENV.read_text(encoding='utf-8').splitlines():
            if line.startswith('SANDBOX_CLUSTER_SECRET='):
                return line.partition('=')[2].strip()
    except OSError:
        return ''
    return ''


def validate_ws_url(value, label):
    parsed = urlsplit(value)
    if parsed.scheme not in ('ws', 'wss') or not parsed.netloc:
        raise ValueError(f'{label} 必须以 ws:// 或 wss:// 开头并包含主机地址')
    return value


def render_worker_yaml(cfg):
    return f"""# Generated by scripts/setup-worker.py; mode 0600
node:
  node_id: "{cfg['node_id']}"
  cluster_secret: "{cfg['cluster_secret']}"
  control_url: "{cfg['control_url']}"
  heartbeat_interval_sec: 3

gateway:
  listen_addr: "{cfg['listen_addr']}"
  public_data_url: "{cfg['public_url']}"
  tls_enabled: false

runtime:
  base_rootfs: "/var/lib/attackbox/base_rootfs"
  instances_dir: "/var/lib/attackbox/instances"
  cgroup_root: "/sys/fs/cgroup/attackbox"
  disk_guard:
    enabled: true
    check_interval_sec: 3
    min_free_space_mb: 5120
    warn_free_space_mb: 10240

network:
  bridge_name: "br-attackbox"
  gateway_ip: "10.200.0.1"
  subnet_cidr: "10.200.0.0/16"
  egress_interface: "{cfg['egress_interface']}"

compose_labs:
  enabled: {str(cfg['compose_enabled']).lower()}
  network_verified: {str(cfg['compose_enabled']).lower()}
  state_dir: "/var/lib/attackbox/compose-labs"
  socket_path: "/var/run/docker.sock"
  pool: "10.202.0.0/16"
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default=str(DEFAULT_WORKER_CONFIG), help='输出配置文件路径（默认 /etc/attackbox/worker.yaml）')
    parser.add_argument('--node-id', default='node-primary', help='节点 ID（默认 node-primary）')
    parser.add_argument('--control-url', default='ws://127.0.0.1:3000/cluster/connect', help='Control 集群连接地址')
    parser.add_argument('--cluster-secret', help='集群通信密钥（同机部署时若留空将自动从 /etc/attackbox/web.env 读取）')
    parser.add_argument('--public-url', default='ws://127.0.0.1:8443', help='浏览器连接网关的外部地址 (public_data_url)')
    parser.add_argument('--listen-addr', default='0.0.0.0:8443', help='Worker 网关监听地址（默认 0.0.0.0:8443）')
    parser.add_argument('--egress-interface', default='', help='宿主机出网网卡名称（默认留空自动按默认路由检测）')
    parser.add_argument('--enable-compose', action='store_true', help='启用 Compose 多容器靶场支持')
    parser.add_argument('--force', action='store_true', help='覆盖已存在的配置文件')
    args = parser.parse_args()

    out_path = Path(args.output)
    if out_path.exists() and not args.force:
        if not sys.stdin.isatty():
            raise ValueError(f'{out_path} 已存在，非交互模式请添加 --force')
        confirm = prompt(f'{out_path} 已存在，是否覆盖？(yes/no)', 'no')
        if confirm.lower() != 'yes':
            print('已取消。')
            return

    cluster_secret = (args.cluster_secret or '').strip() or read_local_cluster_secret()
    if not cluster_secret:
        if not sys.stdin.isatty():
            raise ValueError('未检测到本机 /etc/attackbox/web.env，非交互模式请通过 --cluster-secret 传入集群密钥')
        cluster_secret = prompt('集群密钥 (SANDBOX_CLUSTER_SECRET)')

    if len(cluster_secret) < 32:
        raise ValueError('cluster_secret 长度至少为 32 字符')

    control_url = validate_ws_url(args.control_url.strip(), 'control_url')
    public_url = validate_ws_url(args.public_url.strip(), 'public_url')

    content = render_worker_yaml({
        'node_id': args.node_id.strip(),
        'cluster_secret': cluster_secret,
        'control_url': control_url,
        'public_url': public_url,
        'listen_addr': args.listen_addr.strip(),
        'egress_interface': args.egress_interface.strip(),
        'compose_enabled': args.enable_compose,
    })

    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = out_path.with_name(f'.{out_path.name}.tmp.{os.getpid()}')
    fd = os.open(tmp_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp_path, 0o600)
        os.replace(tmp_path, out_path)
    finally:
        if tmp_path.exists():
            tmp_path.unlink(missing_ok=True)

    print(f'==> Worker 配置文件已写入: {out_path}')
    print(f'    节点 ID:     {args.node_id.strip()}')
    print(f'    Control URL: {control_url}')
    print(f'    Public URL:  {public_url}')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError) as err:
        print(f'配置失败: {err}', file=sys.stderr)
        raise SystemExit(1)
