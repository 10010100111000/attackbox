#!/usr/bin/env bash
# AttackBox Worker (Go 容器沙箱节点) 统一配置与部署脚本
# 用法:
#   sudo ./scripts/worker.sh setup [--node-id ID] [--control-url WS_URL] [--cluster-secret SECRET] [--public-url WS_URL] [--force]
#   ./scripts/worker.sh deploy
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORKER_CONFIG="/etc/attackbox/worker.yaml"
CONTROL_ENV="/etc/attackbox/web.env"
WORKER_BIN="/usr/local/bin/attackbox-worker"

cmd_setup() {
    local node_id="node-primary"
    local control_url="ws://127.0.0.1:3000/cluster/connect"
    local cluster_secret=""
    local public_url="ws://127.0.0.1:8443"
    local listen_addr="0.0.0.0:8443"
    local egress_iface=""
    local compose_enabled="false"
    local force="false"

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --node-id) node_id="$2"; shift 2 ;;
            --control-url) control_url="$2"; shift 2 ;;
            --cluster-secret) cluster_secret="$2"; shift 2 ;;
            --public-url) public_url="$2"; shift 2 ;;
            --listen-addr) listen_addr="$2"; shift 2 ;;
            --egress-interface) egress_iface="$2"; shift 2 ;;
            --enable-compose) compose_enabled="true"; shift ;;
            --force) force="true"; shift ;;
            *) echo "未知参数: $1" >&2; exit 1 ;;
        esac
    done

    if [[ -f "${WORKER_CONFIG}" && "${force}" != "true" ]]; then
        if [[ ! -t 0 ]]; then
            echo "错误: ${WORKER_CONFIG} 已存在，非交互模式请添加 --force" >&2
            exit 1
        fi
        read -r -p "${WORKER_CONFIG} 已存在，是否覆盖？[y/N]: " confirm
        if [[ ! "${confirm}" =~ ^[Yy]$ ]]; then
            echo "已取消。"
            exit 0
        fi
    fi

    # 同机部署自动从 /etc/attackbox/web.env 读取集群密钥
    if [[ -z "${cluster_secret}" && -f "${CONTROL_ENV}" ]]; then
        cluster_secret="$(awk -F= '/^SANDBOX_CLUSTER_SECRET=/{sub(/^[^=]*=/, ""); print; exit}' "${CONTROL_ENV}" | tr -d '\r')"
    fi

    if [[ -z "${cluster_secret}" ]]; then
        if [[ ! -t 0 ]]; then
            echo "错误: 未检测到本机 ${CONTROL_ENV}，非交互模式请通过 --cluster-secret 传入集群密钥" >&2
            exit 1
        fi
        read -r -p "集群密钥 (SANDBOX_CLUSTER_SECRET): " cluster_secret
    fi

    if [[ ${#cluster_secret} -lt 32 ]]; then
        echo "错误: cluster_secret 长度至少为 32 字符" >&2
        exit 1
    fi

    if [[ ! "${control_url}" =~ ^wss?://[^/]+ ]]; then
        echo "错误: control_url 必须以 ws:// 或 wss:// 开头" >&2
        exit 1
    fi

    if [[ ! "${public_url}" =~ ^wss?://[^/]+ ]]; then
        echo "错误: public_url 必须以 ws:// 或 wss:// 开头" >&2
        exit 1
    fi

    mkdir -p "$(dirname "${WORKER_CONFIG}")"
    local tmp_file="${WORKER_CONFIG}.tmp.$$"
    umask 0077
    cat > "${tmp_file}" <<EOF
# Generated by scripts/worker.sh setup; mode 0600
node:
  node_id: "${node_id}"
  cluster_secret: "${cluster_secret}"
  control_url: "${control_url}"
  heartbeat_interval_sec: 3

gateway:
  listen_addr: "${listen_addr}"
  public_data_url: "${public_url}"
  tls_enabled: false

runtime:
  base_rootfs: "/var/lib/attackbox/base_rootfs"
  instances_dir: "/var/lib/attackbox/instances"
  cgroup_root: "/sys/fs/cgroup/attackbox"
  disk_guard:
    enabled: true
    check_interval_sec: 3
    min_free_space_mb: 5120
    warn_free_space_mb: 10240

network:
  bridge_name: "br-attackbox"
  gateway_ip: "10.200.0.1"
  subnet_cidr: "10.200.0.0/16"
  egress_interface: "${egress_iface}"

compose_labs:
  enabled: ${compose_enabled}
  network_verified: ${compose_enabled}
  state_dir: "/var/lib/attackbox/compose-labs"
  socket_path: "/var/run/docker.sock"
  pool: "10.202.0.0/16"
EOF
    chmod 0600 "${tmp_file}"
    mv -f "${tmp_file}" "${WORKER_CONFIG}"

    echo "==> Worker 配置文件已写入: ${WORKER_CONFIG}"
    echo "    节点 ID:     ${node_id}"
    echo "    Control URL: ${control_url}"
    echo "    Public URL:  ${public_url}"
}

cmd_deploy() {
    if ! sudo test -f "${WORKER_CONFIG}"; then
        echo "错误: 缺少 ${WORKER_CONFIG}，请先运行: sudo ./scripts/worker.sh setup" >&2
        exit 1
    fi

    if [[ ! -f "${REPO_ROOT}/dist/attackbox-worker" ]]; then
        echo "错误: 缺少编译产物 dist/attackbox-worker，请先运行: ./scripts/build.sh worker" >&2
        exit 1
    fi

    echo "==> [Worker Deploy] 准备运行目录与安装二进制..."
    sudo install -d -m 0755 /var/lib/attackbox /var/lib/attackbox/instances /var/lib/attackbox/compose-labs
    sudo install -m 0755 -o root -g root "${REPO_ROOT}/dist/attackbox-worker" "${WORKER_BIN}"

    echo "==> [Worker Deploy] 安装并启动 attackbox-worker.service..."
    sudo cp "${REPO_ROOT}/deploy/worker/attackbox-worker.service" /etc/systemd/system/attackbox-worker.service
    sudo systemctl daemon-reload
    sudo systemctl enable attackbox-worker >/dev/null
    sudo systemctl restart attackbox-worker

    local listen_addr
    listen_addr="$(sudo awk -F'"' '/listen_addr:/{print $2}' "${WORKER_CONFIG}" | tail -n1)"
    local listen_port="${listen_addr##*:}"
    listen_port="${listen_port:-8443}"

    echo "==> [Worker Deploy] 执行健康检查 (http://127.0.0.1:${listen_port}/health)..."
    for _ in $(seq 1 30); do
        if curl --fail --silent --show-error --max-time 2 "http://127.0.0.1:${listen_port}/health" >/dev/null; then
            echo "==> [Worker Deploy] 部署成功，Worker 守护进程运行正常。"
            return 0
        fi
        sleep 1
    done

    echo "错误: attackbox-worker 健康检查超时，请查看: sudo journalctl -u attackbox-worker -n 50" >&2
    exit 1
}

ACTION="${1:-}"
shift || true

case "${ACTION}" in
    setup)  cmd_setup "$@" ;;
    deploy) cmd_deploy "$@" ;;
    *)
        echo "用法: $0 {setup|deploy} [参数...]" >&2
        exit 1
        ;;
esac
