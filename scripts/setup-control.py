#!/usr/bin/env python3
"""Generate /etc/attackbox/web.env for the AttackBox Control plane."""
import argparse
import json
import os
from pathlib import Path
import pwd
import re
import secrets
import sys
from urllib.parse import SplitResult, urlsplit

DEFAULT_CONFIG_PATH = Path('/etc/attackbox/web.env')


def prompt(label, default='', secret=False):
    text = f'{label} [{default}]: ' if default else f'{label}: '
    if secret:
        import getpass
        value = getpass.getpass(text).strip()
    else:
        value = input(text).strip()
    return value or default


def validate_postgres_url(value):
    parsed = urlsplit(value)
    if parsed.scheme not in ('postgres', 'postgresql') or not parsed.hostname or not parsed.username or parsed.password is None:
        raise ValueError('PostgreSQL 连接地址必须包含用户名、密码、主机和数据库名')
    if not parsed.path or parsed.path == '/':
        raise ValueError('PostgreSQL 连接地址必须包含数据库名')
    return value


def validate_origin(value):
    parsed = urlsplit(value)
    local = parsed.hostname in ('127.0.0.1', 'localhost')
    if parsed.scheme not in ('http', 'https') or not parsed.netloc:
        raise ValueError('网站访问地址必须包含 http:// 或 https:// 以及主机名')
    if parsed.path not in ('', '/') or parsed.query or parsed.fragment or parsed.username or parsed.password:
        raise ValueError('网站访问地址只能保留协议、域名和可选端口')
    return SplitResult(parsed.scheme, parsed.netloc, '', '', '').geturl(), parsed


def derive_default_public_ws(origin_parsed):
    ws_scheme = 'wss' if origin_parsed.scheme == 'https' else 'ws'
    return f'{ws_scheme}://127.0.0.1:8443'


def format_env(values):
    lines = ['# Generated by scripts/setup-control.py; mode 0600']
    for key, value in values.items():
        text = str(value)
        if '\0' in text or '\n' in text or '\r' in text:
            raise ValueError(f'{key} 不能包含换行或空字节')
        lines.append(f'{key}={text}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default=str(DEFAULT_CONFIG_PATH), help='输出配置文件路径（默认 /etc/attackbox/web.env）')
    parser.add_argument('--database', help='PostgreSQL 连接地址 (DATABASE_URL)')
    parser.add_argument('--origin', help='网站访问地址 (APP_BASE_URL)')
    parser.add_argument('--host', default='127.0.0.1', help='Web 监听地址（默认 127.0.0.1）')
    parser.add_argument('--port', type=int, default=3000, help='Web 监听端口（默认 3000）')
    parser.add_argument('--cluster-secret', help='指定集群通信密钥 SANDBOX_CLUSTER_SECRET（留空自动生成）')
    parser.add_argument('--worker-public-url', help='默认主节点终端网关地址（默认随 origin 协议使用 ws/wss://127.0.0.1:8443）')
    parser.add_argument('--resend-key', default='', help='Resend API Key（可选）')
    parser.add_argument('--mail-from', default='', help='发件人邮箱（可选）')
    parser.add_argument('--force', action='store_true', help='覆盖已存在的配置文件')
    args = parser.parse_args()

    out_path = Path(args.output)
    if out_path.exists() and not args.force:
        if not sys.stdin.isatty():
            raise ValueError(f'{out_path} 已存在，非交互模式请添加 --force')
        confirm = prompt(f'{out_path} 已存在，是否覆盖并重新生成密钥？(yes/no)', 'no')
        if confirm.lower() != 'yes':
            print('已取消。')
            return

    if args.database and args.origin:
        database_url = validate_postgres_url(args.database.strip())
        origin, origin_parsed = validate_origin(args.origin.strip())
        resend_key = args.resend_key.strip()
        mail_from = args.mail_from.strip()
    else:
        if not sys.stdin.isatty():
            raise ValueError('非交互模式必须提供 --database 与 --origin')
        database_url = validate_postgres_url(prompt(
            'PostgreSQL 连接地址',
            args.database or 'postgres://attackbox:CHANGE_ME@127.0.0.1:5432/attackbox_db',
        ))
        origin, origin_parsed = validate_origin(prompt(
            '网站访问地址 (APP_BASE_URL)',
            args.origin or 'http://127.0.0.1',
        ))
        resend_key = prompt('Resend API Key（可选，留空跳过）', args.resend_key, secret=True)
        mail_from = prompt('发件人地址 MAIL_FROM', args.mail_from) if resend_key else ''

    cluster_secret = (args.cluster_secret or '').strip() or secrets.token_hex(32)
    if len(cluster_secret) < 32:
        raise ValueError('SANDBOX_CLUSTER_SECRET 长度至少为 32 字符')

    worker_public_url = (args.worker_public_url or '').strip() or derive_default_public_ws(origin_parsed)
    nodes_json = json.dumps([
        {
            'id': 'node-primary',
            'label': 'Primary Node',
            'publicDataUrl': worker_public_url,
            'maxSlots': 16,
        }
    ], separators=(',', ':'))

    env_values = {
        'NODE_ENV': 'production',
        'PORT': str(args.port),
        'HOST': args.host,
        'DATABASE_URL': database_url,
        'SANDBOX_CONTROL_ENABLED': 'true',
        'SANDBOX_SCHEDULING_ENABLED': 'true',
        'SANDBOX_CLUSTER_SECRET': cluster_secret,
        'SANDBOX_SIGNING_SEED_HEX': secrets.token_hex(32),
        'SANDBOX_NODES_JSON': nodes_json,
        'CONTENT_DATA_DIR': '/var/lib/attackbox-web/content',
        'LAB_DATA_DIR': '/var/lib/attackbox-web/labs',
        'CONTENT_CREDENTIALS_KEY': secrets.token_hex(32),
        'QUIZ_ANSWER_HMAC_SECRET': secrets.token_hex(32),
        'RESEND_API_KEY': resend_key,
        'MAIL_FROM': mail_from,
        'APP_BASE_URL': origin,
    }

    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = out_path.with_name(f'.{out_path.name}.tmp.{os.getpid()}')
    fd = os.open(tmp_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write(format_env(env_values))
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp_path, 0o600)
        try:
            acct = pwd.getpwnam('attackbox')
            os.chown(tmp_path, acct.pw_uid, acct.pw_gid)
        except (KeyError, PermissionError):
            pass
        os.replace(tmp_path, out_path)
    finally:
        if tmp_path.exists():
            tmp_path.unlink(missing_ok=True)

    print(f'==> Control 配置文件已写入: {out_path}')
    print(f'==> 集群密钥 (SANDBOX_CLUSTER_SECRET): {cluster_secret}')
    print('    提示: 同机部署 Worker 时 setup-worker.py 会自动读取此密钥；异机部署 Worker 时请通过 --cluster-secret 传入。')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError) as err:
        print(f'配置失败: {err}', file=sys.stderr)
        raise SystemExit(1)
