import test from 'node:test'
import assert from 'node:assert/strict'
import crypto from 'node:crypto'
import {chromium} from 'playwright'
import {learningFixture} from './helpers/learning-fixture.mjs'
test('challenge lifecycle: staged flags, privacy, throttle, persistence and browser',{skip:!process.env.CONTENT_TEST_DATABASE_URL,timeout:120000},async()=>{
 const f=await learningFixture(),ids=[];let browser,template
 const req=async(p,o)=>(await f.request(p,o)).data
 const draft={title:'Web 挑战 '+crypto.randomUUID().slice(0,8),summary:'逐步找到入口与权限',category:'Web 安全',difficulty:'beginner',bodyMarkdown:'# 实验说明\n\n分析响应并查找 Flag。',targetTemplateId:null,intent:'draft',stages:[{title:'发现入口',promptMarkdown:'找到入口处的 Flag。',hint:'检查页面响应。',flag:'flag{first_secret}'},{title:'进一步探索',promptMarkdown:'完成后续验证。',hint:'关注权限。',flag:'flag{second_secret}'}]}
 const save=async(id,payload,status=200)=>req(id?`/api/admin/challenges/${id}`:'/api/admin/challenges',{actor:f.admin,method:id?'PUT':'POST',body:payload,status})
 try{
  const alice=await f.account(),bob=await f.account()
  template=await req('/api/admin/target-templates',{actor:f.admin,method:'POST',body:{name:'挑战教学环境',description:'测试目标',image:'private.example/lab:1',sourceUrl:'https://private.example/project',enabled:true,ports:[],accessInstructions:'查看响应'}})
  draft.targetTemplateId=template.id
  await f.request('/api/admin/challenges',{status:401});await f.request('/api/admin/challenges',{actor:alice,status:403});await f.request('/api/me/challenges',{status:401})
  await save(null,{...draft,intent:'publish',stages:[]},400)
  const created=await save(null,draft);ids.push(created.id);const path=`/api/challenges/${created.id}`,admin=`/api/admin/challenges/${created.id}`
  await f.request(path,{status:404})
  let d=await req(admin,{actor:f.admin});assert.equal(d.stages[0].flag,draft.stages[0].flag)
  await save(created.id,{...draft,intent:'publish',lockVersion:d.lockVersion,stages:d.stages})
  await save(created.id,{...draft,lockVersion:d.lockVersion},409)
  d=await req(path);assert.equal(d.stages[1].locked,true);assert.equal(d.target.name,template.name);assert.ok(!JSON.stringify(d).includes('private.example'))
  await req(`/api/admin/target-templates/${template.id}`,{actor:f.admin,method:'PUT',body:{...template,enabled:false}})
  assert.deepEqual((await req(path)).target,{status:'unavailable'})
  await save(null,{...draft,intent:'draft'},400)
  const retained=await req(admin,{actor:f.admin});await save(created.id,{...draft,intent:'publish',lockVersion:retained.lockVersion,stages:retained.stages})
  await req(`/api/admin/target-templates/${template.id}`,{actor:f.admin,method:'PUT',body:{...template,enabled:true,lockVersion:template.lockVersion+1}})
  for(const text of ['first_secret','second_secret','flagHmac','flag_hmac'])assert.ok(!JSON.stringify(d).includes(text))
  const attempt=(index,flag,actor=alice,status=200)=>req(path+'/attempt',{actor,method:'POST',body:{stageId:d.stages[index].id,flag},status})
  await attempt(0,'flag{first_secret}',null,401)
  await attempt(1,'flag{second_secret}',alice,403)
  assert.equal((await attempt(0,'FLAG{FIRST_SECRET}')).correct,false)
  const concurrent=await Promise.all([attempt(0,' flag{first_secret} '),attempt(0,'flag{first_secret}')]);assert.ok(concurrent.every(r=>r.correct))
  assert.equal((await req(path,{actor:alice})).completedStages,1);assert.equal((await req(path,{actor:bob})).completedStages,0)
  await attempt(1,'flag{second_secret}')
  assert.equal((await req(path,{actor:alice})).isCompleted,true)
  assert.equal((await req('/api/me/challenges',{actor:alice}))[0].completedStages,2)
  assert.deepEqual(await req('/api/me/challenges',{actor:bob}),[])
  for(let i=0;i<20;i++)await attempt(0,'wrong',bob)
  await attempt(0,'flag{first_secret}',bob,429)
  await f.sql`update challenge_attempt_limits set window_at=now()-interval '2 minutes' where user_id=${bob.id}`
  assert.equal((await attempt(0,'flag{first_secret}',bob)).correct,true)
  let edit=await req(admin,{actor:f.admin})
  await save(created.id,{...draft,intent:'publish',lockVersion:edit.lockVersion,stages:edit.stages.map((s,i)=>({...s,flag:i?'flag{changed}':s.flag}))})
  assert.equal((await req(path,{actor:alice})).isCompleted,true)
  const csrf=await fetch(f.base+admin,{method:'PUT',headers:{cookie:`attackbox_session=${f.admin.token}`,origin:'https://other.invalid','content-type':'application/json'},body:JSON.stringify(draft)});assert.equal(csrf.status,403)
  browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']})
  const adminCtx=await browser.newContext({viewport:{width:1440,height:1000}});await adminCtx.addCookies([{name:'attackbox_session',value:f.admin.token,url:f.base}])
  const p=await adminCtx.newPage();await p.goto(f.base+`/admin/challenges/${created.id}`)
  await p.getByLabel('标题 *',{exact:true}).fill(draft.title+' 编辑')
  await p.getByRole('button',{name:'添加阶段',exact:true}).click()
  await p.getByLabel('标准 Flag',{exact:true}).last().fill('flag{third_secret}')
  await p.getByRole('button',{name:'保存并发布',exact:true}).click();await p.getByText('已保存并发布',{exact:true}).waitFor()
  const before=await req(admin,{actor:f.admin});assert.equal(before.stages.length,3)
  await p.getByLabel('简介',{exact:true}).fill('重新保存不丢失阶段标识')
  await p.getByRole('button',{name:'保存并发布',exact:true}).click();await p.getByText('已保存并发布',{exact:true}).waitFor()
  assert.deepEqual((await req(admin,{actor:f.admin})).stages.map(s=>s.id),before.stages.map(s=>s.id))
  const userCtx=await browser.newContext({viewport:{width:1440,height:1000}});await userCtx.addCookies([{name:'attackbox_session',value:alice.token,url:f.base}])
  const read=await userCtx.newPage();await read.goto(f.base+`/challenges/${created.id}`)
  await read.getByLabel('阶段 3 Flag',{exact:true}).fill('flag{third_secret}')
  await read.getByRole('button',{name:'提交 Flag',exact:true}).click();await read.getByText('挑战已完成',{exact:true}).waitFor()
  assert.equal(await read.getByRole('button',{name:'提交 Flag',exact:true}).count(),0)
  await read.reload();await read.getByText('挑战已完成',{exact:true}).waitFor()
  await read.screenshot({path:'/tmp/attackbox-challenge.png',fullPage:true})
  await p.goto(f.base+'/admin/challenges/new')
  await p.getByRole('heading',{name:'新建挑战',exact:true}).waitFor()
  assert.equal((await req('/api/admin/challenges',{actor:f.admin})).length,1)
  await p.getByLabel('标题 *',{exact:true}).fill('浏览器新建挑战')
  await p.getByLabel('挑战正文',{exact:true}).fill('## 新挑战\n查找环境中的 Flag。')
  await p.getByRole('button',{name:'添加阶段',exact:true}).click()
  await p.getByLabel('标准 Flag',{exact:true}).fill('flag{browser_secret}')
  const posted=p.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname==='/api/admin/challenges')
  await p.getByRole('button',{name:'保存并发布',exact:true}).click()
  const newId=(await(await posted).json()).data.id;ids.push(newId)
  await p.waitForURL(`**/admin/challenges/${newId}`)
  const guest=await browser.newContext(),guestPage=await guest.newPage()
  await guestPage.goto(f.base+`/challenges/${newId}`)
  await guestPage.getByRole('link',{name:'登录后提交 Flag',exact:true}).waitFor()
  assert.ok(!(await guestPage.content()).includes('browser_secret'))
  edit=await req(admin,{actor:f.admin});await save(created.id,{...draft,lockVersion:edit.lockVersion,stages:edit.stages,intent:'draft'})
  await f.request(path,{status:404});await attempt(0,'flag{first_secret}',alice,404)
  assert.deepEqual(await req('/api/me/challenges',{actor:alice}),[])
  assert.equal((await f.sql`select count(*)::int as count from challenge_completions where user_id=${alice.id}`)[0].count,3)
 }finally{await browser?.close();for(const id of ids)await f.sql`delete from challenges where id=${id}`;if(template)await f.sql`delete from target_templates where id=${template.id}`;await f.cleanup()}
})
